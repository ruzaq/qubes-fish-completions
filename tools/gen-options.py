#!/usr/bin/env python3
"""Generate option completions from dumped `--help` of qvm-* tools.

Usage: python3 tools/gen-options.py help/<version>

For every help/<version>/<cmd>.txt with an existing completions/<cmd>.fish,
the block between GEN_BEGIN and GEN_END in that file is replaced. Everything
outside the block (positional-argument logic) is hand-written and kept.

The block defines:
  - one `complete` line per option alias, with the help text as description
  - options of subcommands, conditioned on the subcommand being present
  - __qvm_valopts_<cmd>: options that take a value, so __qvm_pos_args can
    skip their values when counting positional arguments
  - __qvm_subs_<cmd>: subcommand names with descriptions
"""
import os
import re
import sys

GEN_BEGIN = '# BEGIN generated by tools/gen-options.py, do not edit by hand'
GEN_END = '# END generated'

COMMON = {'--verbose', '-v', '--quiet', '-q', '--help', '-h', '--version'}

# Value completers keyed by option name. Anything matching FILE_HINTS gets
# file completion, everything else is free text.
VALUE_COMPLETERS = {
    '--exclude': '(__qvm_vms)',
    '--dest-vm': '(__qvm_running_vms)',
    '--template': '(__qvm_templates)',
    '--template-source': '(__qvm_templates)',
    '--pool': '(__qvm_pools)',
    '--updatevm': '(__qvm_running_vms)',
    '--dispvm': '(__qvm_vms)',
    '--profile': '(__qvm_backup_profiles)',
    '--user': 'root user',
    '--label': 'red orange yellow green gray blue purple black',
    '--class': 'AppVM StandaloneVM TemplateVM DispVM',
    '--netvm-is': '(__qvm_vms)',
    '--servicevm': 'True False',
    '--internal': 'True False',
}
FILE_HINTS = re.compile(r'file|dir|keyring|cdrom|drive|hddisk|import|PATH|FILE', re.I)

# Per-command completers, checked before VALUE_COMPLETERS (same option name
# means different things in different tools, e.g. --set).
CMD_COMPLETERS = {
    ('qvm-pool', '--info'): '(__qvm_pools)',
    ('qvm-pool', '--remove'): '(__qvm_pools)',
    ('qvm-pool', '--set'): '(__qvm_pools)',
    ('qvm-ls', '--fields'): 'name class state label template netvm memory disk ip tags',
    ('qvm-ls', '--sort'): 'name class state label template netvm memory disk ip',
    ('qvm-backup', '--compress-filter'): 'gzip bzip2 xz zstd',
}

# Descriptions for subcommand-only options (they have no help text of their
# own in the main --help output).
SUB_DESC = {
    '--option': 'Device option (key=value)',
    '--ro': 'Attach read-only',
    '--persistent': 'Keep attached across restarts',
    '--ask': 'Ask before attaching',
    '--required': 'Always attach, refuse start without it',
    '--port': 'Match by port',
    '--device': 'Match by device identity',
    '--assignments': 'Show assigned devices',
    '--with-sbdf': 'Show PCI SBDF address',
    '--all': 'All qubes',
    '--exclude': 'Exclude qube',
    '--before': 'Insert before rule number',
    '--rule-no': 'Rule number to remove',
    '--force': 'Force the operation',
    '--full': 'Show all revisions',
    '--size': 'New volume size',
    '--no-resize': 'Do not resize the volume',
    '--pool': 'Storage pool',
    '-p': 'Storage pool',
    '--allow-pv': 'Allow PV virtualization mode',
    '--skip-start': 'Do not start the template',
    '--downloaddir': 'Download directory',
    '--retries': 'Download retries',
    '--nogpgcheck': 'Skip signature check',
}


def fish_quote(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def var_name(cmd):
    return cmd.replace('-', '_')


def parse_main_options(text):
    """Return list of (aliases, takes_value, description) from 'options:'."""
    out = []
    in_opts = False
    group_desc = prev_heading = False
    for line in text.splitlines():
        if line.startswith("Command '"):
            break  # per-subcommand usage, handled by parse_subcommands
        if line and not line.startswith(' '):
            # Every heading except these starts an option group
            # ("options:", "Formatting options:", "Profile setup:", ...)
            in_opts = line.rstrip().endswith(':') and not line.startswith(
                ('positional arguments', 'commands', 'usage'))
            group_desc = False
            prev_heading = in_opts
            if in_opts:
                out.append(None)  # group break, stops description continuation
            continue
        if not in_opts:
            continue
        if prev_heading:
            # A group may start with a prose description up to a blank line,
            # which can itself begin with an option name ("--profile option)").
            group_desc = not re.match(r'^  -', line)
            prev_heading = False
        if group_desc:
            group_desc = bool(line.strip())
            continue
        m = re.match(r'^  (-\S.*?)(?:\s{2,}(\S.*))?$', line)
        if m:
            parts = m.group(1).split(', ')
            takes = any(' ' in p.strip() for p in parts)
            aliases = [p.strip().split(' ')[0] for p in parts]
            out.append([aliases, takes, m.group(2) or ''])
        elif out and out[-1] is not None and re.match(r'^\s{6,}\S', line):
            out[-1][2] = (out[-1][2] + ' ' + line.strip()).strip()
    return [o for o in out if o is not None]


def parse_subcommands(text):
    """Return {name: (aliases, description)} and {name: [(opt, takes)]}."""
    subs = {}
    m = re.search(r'^\s+\{([\w,-]+)\}\s*$', text, re.M)
    if not m:
        return {}, {}
    names = m.group(1).split(',')
    for line in text.splitlines():
        mm = re.match(r'^    ([\w-]+)(?: \(([\w,-]+)\))?\s{2,}(\S.*)$', line)
        if mm and mm.group(1) in names:
            aliases = mm.group(2).split(',') if mm.group(2) else []
            subs[mm.group(1)] = (aliases, mm.group(3))
    for n in names:  # names without a description line
        if n not in subs and not any(n in a for a, _ in subs.values()):
            subs[n] = ([], '')
    subopts = {}
    for block in re.split(r"^Command '", text, flags=re.M)[1:]:
        name = block.split("'", 1)[0]
        usage = ' '.join(block.splitlines()[1:])
        opts = []
        for br in re.findall(r'\[([^\[\]]*(?:\[[^\[\]]*\][^\[\]]*)*)\]', usage):
            for alt in br.split('|'):
                om = re.match(r'\s*(--?[\w-]+)(\s+\S+)?', alt)
                if om and om.group(1) not in COMMON:
                    opts.append((om.group(1), bool(om.group(2))))
        subopts[name] = opts
    return subs, subopts


def complete_line(cmd, opt, takes, desc, cond=None, key=None):
    parts = ['complete', '-c', cmd]
    if cond:
        parts += ['-n', fish_quote(cond)]
    if opt.startswith('--'):
        parts += ['-l', opt[2:]]
    elif len(opt) == 2:
        parts += ['-s', opt[1]]
    else:
        parts += ['-o', opt[1:]]
    if takes:
        comp = CMD_COMPLETERS.get((cmd, key or opt)) or VALUE_COMPLETERS.get(key or opt)
        if comp:
            parts += ['-x', '-a', fish_quote(comp)]
        elif FILE_HINTS.search(opt + ' ' + desc):
            parts += ['-r', '-F']
        else:
            parts += ['-x']
    if desc:
        d = re.sub(r'\s+', ' ', desc).strip()
        d = d[0].upper() + d[1:]
        if len(d) > 70:
            d = d[:67].rstrip() + '...'
        parts += ['-d', fish_quote(d)]
    return ' '.join(parts)


def generate(cmd, text):
    lines = [GEN_BEGIN]
    opts = parse_main_options(text)
    # short alias shares the completer of its long alias
    long_of = {}
    for aliases, takes, desc in opts:
        longs = [a for a in aliases if a.startswith('--')]
        for a in aliases:
            if not a.startswith('--') and longs:
                long_of[a] = longs[0]
    valopts = []
    for aliases, takes, desc in opts:
        for a in aliases:
            lines.append(complete_line(cmd, a, takes, desc, key=long_of.get(a, a)))
            if takes:
                valopts.append(a)
    subs, subopts = parse_subcommands(text)
    for name, opts_ in subopts.items():
        aliases = [name] + subs.get(name, ([], ''))[0]
        cond = '__fish_seen_subcommand_from ' + ' '.join(aliases)
        for opt, takes in opts_:
            lines.append(complete_line(cmd, opt, takes, SUB_DESC.get(opt, ''), cond))
            if takes:
                valopts.append(opt)
    v = var_name(cmd)
    lines.append(f'set -g __qvm_valopts_{v} ' + ' '.join(sorted(set(valopts))))
    if subs:
        items = [f"{n}\\t{fish_quote(d[0].upper() + d[1:])}" if d else n
                 for n, (_, d) in subs.items()]
        lines.append(f'set -g __qvm_subs_{v} ' + ' '.join(items))
    lines.append(GEN_END)
    return '\n'.join(lines) + '\n'


def splice(path, block):
    old = open(path).read() if os.path.exists(path) else ''
    if GEN_BEGIN in old:
        head, rest = old.split(GEN_BEGIN, 1)
        tail = rest.split(GEN_END, 1)[1].lstrip('\n')
        new = head + block + tail
    else:
        new = old.rstrip('\n') + '\n\n' + block if old else block
    with open(path, 'w') as f:
        f.write(new)


def main():
    helpdir = sys.argv[1]
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    done = []
    for fn in sorted(os.listdir(helpdir)):
        if fn.startswith('_') or not fn.endswith('.txt'):
            continue
        cmd = fn[:-4]
        target = os.path.join(root, 'completions', cmd + '.fish')
        if not os.path.exists(target):
            print(f'skip {cmd}: no completions/{cmd}.fish')
            continue
        splice(target, generate(cmd, open(os.path.join(helpdir, fn)).read()))
        done.append(cmd)
    print(f'generated {len(done)} files')


if __name__ == '__main__':
    main()
